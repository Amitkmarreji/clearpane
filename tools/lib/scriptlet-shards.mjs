// Writes scriptlets/shard-N.js files: each is the scriptlet library plus the
// hostname table for one slice of sites, registered by the background
// script to run only on those sites (the uBO Lite approach).
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

const SHARDS = 16;
// Entities (example.*) can't be written as match patterns, so the shard is
// registered on these common TLDs and the library checks the hostname itself.
// Kept short: every entity costs one match pattern per TLD.
const ENTITY_TLDS = ['com', 'net', 'org', 'info', 'io', 'co', 'me', 'tv', 'cc', 'to', 'xyz', 'top',
  'site', 'online', 'live', 'pro', 'ru', 'de', 'fr', 'it', 'es', 'pl', 'nl', 'in', 'co.uk', 'com.br',
  'eu', 'one', 'vip', 'fun'];
const HOST = /^[a-z0-9-]+(\.[a-z0-9-]+)+$/;
const IP = /^\d+\.\d+\.\d+\.\d+$/;

// Shard by the label before the TLD ("example" for example.com, a.example.com
// and example.*), so a site's rules and its exceptions land in the same file.
function shardOf(key) {
  const labels = key.split('.');
  const base = labels.length > 1 ? labels[labels.length - 2] : key;
  let h = 0;
  for (const ch of base) h = (h * 31 + ch.charCodeAt(0)) >>> 0;
  return h % SHARDS;
}

function matchPatterns(key) {
  if (key.endsWith('.*')) {
    const name = key.slice(0, -2);
    if (!HOST.test(`${name}.com`)) return [];
    return ENTITY_TLDS.map(tld => `*://*.${name}.${tld}/*`);
  }
  if (IP.test(key)) return [`*://${key}/*`];
  return HOST.test(key) ? [`*://*.${key}/*`] : [];
}

export async function writeScriptletShards(root, scriptlets, exceptions) {
  const lib = await readFile(join(root, 'src', 'scriptlets', 'lib.js'), 'utf8');
  const shards = Array.from({ length: SHARDS }, () => ({ s: {}, e: {}, matches: new Set() }));
  for (const [key, calls] of Object.entries(scriptlets)) {
    const patterns = matchPatterns(key);
    if (!patterns.length) continue;
    const shard = shards[shardOf(key)];
    shard.s[key] = calls;
    patterns.forEach(p => shard.matches.add(p));
  }
  for (const [key, list] of Object.entries(exceptions)) shards[shardOf(key)].e[key] = list;

  await rm(join(root, 'scriptlets'), { recursive: true, force: true });
  await mkdir(join(root, 'scriptlets'), { recursive: true });
  const registrations = [];
  let hosts = 0;
  for (let i = 0; i < SHARDS; i++) {
    const { s, e, matches } = shards[i];
    if (!matches.size) continue;
    hosts += Object.keys(s).length;
    const file = `scriptlets/shard-${i}.js`;
    const body = `// Generated by tools/build.mjs - do not edit.\n(function () {\n${lib}\nrunShard(${JSON.stringify({ s, e })});\n})();\n`;
    await writeFile(join(root, file), body);
    registrations.push({ id: `scriptlets-${i}`, js: [file], matches: [...matches].sort() });
  }
  await writeFile(join(root, 'data', 'scriptlets.json'), JSON.stringify(registrations));
  return { summary: { shards: registrations.length, hosts } };
}
